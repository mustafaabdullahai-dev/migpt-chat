_MODULE = object()          # sentinel returned for `np` / `numpy`
_LINALG = object()          # sentinel returned for `np.linalg`


def _np_attr(name: str) -> Any:
    if _np is None:
        raise ValueError("numpy is not installed")
    return getattr(_np, name)


def _np_linalg(name: str) -> Any:
    if _np is None:
        raise ValueError("numpy is not installed")
    return getattr(_np.linalg, name)


