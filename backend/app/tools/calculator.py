"""Safe universal calculator.

Parses expressions with the `ast` module and evaluates ONLY a whitelisted grammar:
pure math (math module) + a fixed set of numpy functions (np.array, matrices,
linalg, statistics, etc.). numpy is usable through its plain function names AND
`np.` / `np.linalg.` prefixes, but only attributes on an explicit allow-list may
be reached. Never uses eval()/exec() and never runs code generated by the LLM.
"""

