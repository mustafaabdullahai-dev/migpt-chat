class CalculatorArgs(BaseModel):
    expression: str = Field(
        ...,
        description=(
            "A math expression with numbers and operators. Support: + - * / // % **, "
            "parentheses, percentages (e.g. '17.5% of 85000' -> 0.175*85000), functions "
            "sqrt/log/log10/log2/exp/(hyperbolic) trig/ceil/floor/abs/round/min/max/"
            "factorial/gcd/lcm/degrees/radians and constants pi/e/tau/phi. numpy is also "
            "available: arrays via array([1,2,3]) or np.array, matrix ops "
            "dot/matmul/inner/outer/cross, linalg det/inv/solve/norm/rank/eigvals, statistics "
            "mean/median/std/var/percentile/cumsum/prod, construction arange/zeros/ones/eye/"
            "linspace/reshape/transpose. Use plain names or np./np.linalg. prefixes. "
            "Do NOT include variable assignments, text, currency symbols or commas as "
            "thousands separators."
        ),
    )


def evaluate(expression: str) -> CalculationResult:
    expression = expression.strip()
    if not expression:
        raise ValueError("Empty expression")
    # Reject anything that could smuggle code
    for forbidden in ("@", ";", "lambda", "exec(", "eval(", "open(", "__", "await"):
        if forbidden in expression:
            raise ValueError(f"Forbidden token in expression: {forbidden!r}")

    tree = ast.parse(expression, mode="eval")
    steps: list[str] = []
    value = _eval_node(tree.body, steps)
    if isinstance(value, float):
        value = round(value, 10)  # neutralize fp noise like 0.175*85000
    return CalculationResult(expression=expression, result=_coerce(value), steps=steps)


def _coerce(value: Any) -> Any:
    """Normalizes numpy scalars/arrays to JSON-safe numbers or nested lists."""
    if _np is not None:
        if isinstance(value, _np.ndarray):
            try:
                return value.tolist()
            except Exception:
                return "array"
        if isinstance(value, (_np.integer, _np.floating, _np.bool_)):
            value = value.item()
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, tuple):
        return [_coerce(v) for v in value]
    if isinstance(value, float):
        return round(value, 10)
    return value


def _plain(value: Any) -> str:
    """Human-readable display of a value (number, list/matrix, numpy scalar)."""
    value = _coerce(value)
    if isinstance(value, list):
        return _fmt_matrix(value)
    if isinstance(value, (int, float)):
        return f"{value:g}"
    return str(value)


def _fmt_matrix(matrix: Any) -> str:
    if not isinstance(matrix, list):
        return str(matrix)
    if not matrix or not isinstance(matrix[0], list):
        return repr(matrix)
    rows = ", ".join(str(r) for r in matrix)
    return f"[{rows}]"


def _func_name(node: ast.AST) -> str:
    parts: list[str] = []
    cur = node
    while isinstance(cur, ast.Attribute):
        parts.append(cur.attr)
        cur = cur.value
    if isinstance(cur, ast.Name):
        parts.append(cur.id)
    return ".".join(reversed(parts)).replace("np.", "np.").replace("numpy.", "np.")


def _eval_node(node: ast.AST, steps: list[str]) -> Any:
    if isinstance(node, ast.Expression):
        return _eval_node(node.body, steps)
    if isinstance(node, ast.Constant):
        if isinstance(node.value, bool):
            raise ValueError("Boolean literals are not allowed")
        if isinstance(node.value, (int, float)):
            return node.value
        raise ValueError("Only numeric constants are allowed")
    if isinstance(node, ast.Name):
        if node.id in _CONSTANTS:
            return _CONSTANTS[node.id]
        if node.id in _ALLOWED_FUNCS:
            return _ALLOWED_FUNCS[node.id]
        if node.id in ("np", "numpy"):
            if _np is None:
                raise ValueError("numpy is not installed")
            return _MODULE
        raise ValueError(f"Unknown symbol: {node.id!r}")
    if isinstance(node, ast.Attribute):
        base_val = _eval_node(node.value, steps)
        if base_val is _MODULE:
            if node.attr == "linalg":
                return _LINALG
            if node.attr in _NP_ATTRS:
                return _NP_ATTRS[node.attr]
            raise ValueError(f"numpy attribute not allowed: {node.attr!r}")
        if base_val is _LINALG:
            if node.attr in _NP_LINALG_ATTRS:
                return _NP_LINALG_ATTRS[node.attr]
            raise ValueError(f"numpy.linalg attribute not allowed: {node.attr!r}")
        raise ValueError("Only np.<func> attribute access is allowed")
    if isinstance(node, ast.BinOp):
        if type(node.op) not in _BINOPS:
            raise ValueError(f"Operator not allowed: {type(node.op).__name__}")
        left = _eval_node(node.left, steps)
        right = _eval_node(node.right, steps)
        try:
            result = _BINOPS[type(node.op)](left, right)
        except Exception as exc:
            raise ValueError(f"Operation failed: {exc}") from exc
        _record_step(steps, left, right, result, type(node.op))
        return result
    if isinstance(node, ast.UnaryOp):
        if type(node.op) not in _UNBINOPS:
            raise ValueError(f"Unary operator not allowed: {type(node.op).__name__}")
        value = _eval_node(node.operand, steps)
        return _UNBINOPS[type(node.op)](value)
    if isinstance(node, ast.Call):
        func_val = _eval_node(node.func, steps)
        if not callable(func_val):
            raise ValueError("Not a callable: %s" % _func_name(node.func))
        if node.keywords:
            raise ValueError("Keyword arguments are not allowed")
        args = [_eval_node(a, steps) for a in node.args]
        name = _func_name(node.func)
        try:
            result = func_val(*args)
        except Exception as exc:
            raise ValueError(f"{name}(...) failed: {exc}") from exc
        args_desc = ", ".join(_plain(a) for a in args)
        steps.append(f"{name}({args_desc}) = {_plain(result)}")
        return _coerce(result)
    if isinstance(node, ast.List):
        return [_eval_node(e, steps) for e in node.elts]
    if isinstance(node, ast.Tuple):
        return tuple(_eval_node(e, steps) for e in node.elts)
    if isinstance(node, _UNSAFE_NODES):
        raise ValueError(f"Syntax not allowed: {type(node).__name__}")
    raise ValueError(f"Syntax not allowed: {type(node).__name__}")


def _record_step(steps: list[str], left: Any, right: Any, result: Any, op_type: type) -> None:
    sym = {
        ast.Add: "+",
        ast.Sub: "-",
        ast.Mult: "*",
        ast.Div: "/",
        ast.FloorDiv: "//",
        ast.Mod: "%",
        ast.Pow: "^",
    }.get(op_type, "?")
    l = _plain(left)
    r = _plain(right)
    res = _plain(result)
    if sym == "^":
        steps.append(f"{l} ** {r} = {res}")
    else:
        steps.append(f"{l} {sym} {r} = {res}")